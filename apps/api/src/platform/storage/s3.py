        def _call() -> None:
            with _managed_s3_client(self._client()) as client:
                client.copy_object(
                    Bucket=self.bucket,
                    Key=dest_key,
                    CopySource={"Bucket": source_bucket, "Key": source_key},
                )

        await run_s3_blocking_call(_call)

