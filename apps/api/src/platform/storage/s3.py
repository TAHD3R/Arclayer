    async def presign_upload_part(
        self,
        *,
        object_key: str,
        upload_id: str,
        part_number: int,
        expires_in: int,
    ) -> PresignedPart:
        def _call() -> PresignedPart:
            with _managed_s3_client(self._client()) as client:
                url = client.generate_presigned_url(
                    ClientMethod="upload_part",
                    Params={
                        "Bucket": self.bucket,
                        "Key": object_key,
                        "UploadId": upload_id,
                        "PartNumber": int(part_number),
                    },
                    ExpiresIn=int(expires_in),
                )
                return PresignedPart(url=url, method="PUT", headers={})

        return await run_s3_blocking_call(_call)

    async def complete_multipart_upload(
        self,
        *,
        object_key: str,
        upload_id: str,
        parts: list[dict[str, Any]],
    ) -> None:
        """
        parts: list of {"ETag": "...", "PartNumber": 1}
        """

        def _call() -> None:
            with _managed_s3_client(self._client()) as client:
                from botocore.exceptions import ClientError  # type: ignore[import-not-found]

                try:
                    client.complete_multipart_upload(
                        Bucket=self.bucket,
                        Key=object_key,
                        UploadId=upload_id,
                        MultipartUpload={"Parts": parts},
                    )
                except ClientError as exc:
                    code = str((exc.response or {}).get("Error", {}).get("Code") or "")
                    if code == "NoSuchUpload":
                        raise StorageMultipartUploadNotFoundError(
                            provider=self.provider,
                            object_key=object_key,
                            upload_id=upload_id,
                        ) from exc
                    raise

        await run_s3_blocking_call(_call)

    async def abort_multipart_upload(self, *, object_key: str, upload_id: str) -> None:
        def _call() -> None:
            with _managed_s3_client(self._client()) as client:
                from botocore.exceptions import ClientError  # type: ignore[import-not-found]

                try:
                    client.abort_multipart_upload(
                        Bucket=self.bucket,
                        Key=object_key,
                        UploadId=upload_id,
                    )
                except ClientError as exc:
                    code = str((exc.response or {}).get("Error", {}).get("Code") or "")
                    if code == "NoSuchUpload":
                        # Abort is idempotent: the upload may already be completed/aborted/expired.
                        return
                    raise

        await run_s3_blocking_call(_call)

    async def presign_get_object(
        self,
        *,
        object_key: str,
        expires_in: int,
        response_content_type: str | None = None,
        response_content_disposition: str | None = None,
    ) -> str:
        def _call() -> str:
            with _managed_s3_client(self._client()) as client:
                params: dict[str, Any] = {"Bucket": self.bucket, "Key": object_key}
                if response_content_type:
                    params["ResponseContentType"] = response_content_type
                if response_content_disposition:
                    params["ResponseContentDisposition"] = response_content_disposition
                return str(
                    client.generate_presigned_url(
                        ClientMethod="get_object",
                        Params=params,
                        ExpiresIn=int(expires_in),
                    )
                )

        return await run_s3_blocking_call(_call)
