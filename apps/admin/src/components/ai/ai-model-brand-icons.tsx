import { cn } from "@arclayer/lib/utils";

type AIModelBrandIconProps = {
  provider?: string | null;
  modelId?: string | null;
  auto?: boolean;
  className?: string;
};

export function AIModelBrandIcon({ provider, modelId, auto, className }: AIModelBrandIconProps) {
  const brand = auto ? "auto" : resolveModelBrand(provider, modelId);
  const iconClassName = "size-full";

  return (
    <span
      className={cn(
        "flex size-4 shrink-0 items-center justify-center rounded-full text-label-secondary",
        className,
      )}
      aria-hidden="true"
    >
      {brand === "auto" ? (
        <RouteIcon className={iconClassName} />
      ) : brand === "deepseek" ? (
        <DeepSeekIcon className={iconClassName} />
      ) : brand === "anthropic" ? (
        <AnthropicIcon className={iconClassName} />
      ) : brand === "codex" ? (
        <CodexIcon className={iconClassName} />
      ) : brand === "glm" ? (
        <GLMIcon className={iconClassName} />
      ) : brand === "gpt-image" ? (
        <GPTImageIcon className={iconClassName} />
      ) : (
        <OpenAIIcon className={iconClassName} />
      )}
    </span>
  );
}

function resolveModelBrand(provider?: string | null, modelId?: string | null) {
  const value = `${provider ?? ""} ${modelId ?? ""}`.toLocaleLowerCase();
  if (value.includes("codex")) return "codex";
  if (value.includes("gpt-image") || value.includes("image2") || value.includes("image-2")) {
    return "gpt-image";
  }
  if (value.includes("glm") || value.includes("zhipu") || value.includes("bigmodel")) {
    return "glm";
  }
  if (value.includes("deepseek")) return "deepseek";
  if (value.includes("anthropic") || value.includes("claude")) return "anthropic";
  return "openai";
}

