const runtimeErrorCodes = ["PROVIDER_MODEL_CONFIGURATION_CONFLICT"] as const;

function errorMessages(locale: "en-US" | "zh-CN"): Record<string, string> {
  return JSON.parse(
    readFileSync(resolve(process.cwd(), "locales", locale, "errors.json"), "utf8"),
  ) as Record<string, string>;
}

describe("AI provider error locales", () => {
  it.each(["zh-CN", "en-US"] as const)("covers every provider error in %s", (locale) => {
    const messages = errorMessages(locale);

    for (const code of [
      ...providerErrorCodes,
      ...workspaceRolloutErrorCodes,
      ...runtimeErrorCodes,
    ]) {
      expect(messages[code], `${locale} is missing ${code}`).toBeTruthy();
    }
  });
});
